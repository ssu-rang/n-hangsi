const uniqueDailyWords = [...new Set(dailyWords)];
const rotationStart = Date.UTC(2026, 7, 28);
const millisecondsPerDay = 24 * 60 * 60 * 1_000;
const rotationStep = 197;
const rotationOffset = 113;

if (uniqueDailyWords.length !== dailyWords.length) {
  throw new Error('Daily word list contains duplicates');
}

export function dailyWord(now = new Date()): string {
  const koreaDate = new Date(now.getTime() + 9 * 60 * 60 * 1_000);
  const koreaDay = Date.UTC(koreaDate.getUTCFullYear(), koreaDate.getUTCMonth(), koreaDate.getUTCDate());
  const elapsedDays = Math.floor((koreaDay - rotationStart) / millisecondsPerDay);
  const index = modulo(elapsedDays * rotationStep + rotationOffset, uniqueDailyWords.length);
  return uniqueDailyWords[index]!;
}

export function dailyWordCount(): number {
  return uniqueDailyWords.length;
}

function modulo(value: number, divisor: number): number {
  return ((value % divisor) + divisor) % divisor;
}
